'use strict';
const assert=require('node:assert/strict');
const {createTimelineJournal}=require('../timeline-sync-journal.js');
global.createTimelineJournal=createTimelineJournal;
const {createTripTimelineJournal}=require('../timeline-trip-journal.js');
const map=new Map();const storage={getItem:k=>map.has(k)?map.get(k):null,setItem:(k,v)=>map.set(k,v)};
const a=createTripTimelineJournal(storage,{tripId:'vn-real'});
const b=createTripTimelineJournal(storage,{tripId:'vn-other'});
const c=createTripTimelineJournal(storage,{tripId:'vn-real',environment:'staging'});
a.enqueue({day:'4',items:[{id:'keep',notes:'manual'}]});
b.enqueue({day:'4',items:[{id:'other'}]});
c.enqueue({day:'test-day-4',items:[{id:'fake'}]});
assert.equal(a.read().changes[0].items[0].notes,'manual');
assert.equal(b.read().changes[0].items[0].id,'other');
assert.equal(c.read().changes[0].items[0].id,'fake');
assert.equal(map.has('vn_timeline_pending_v1'),false);
const x=a.enqueue({day:'5',items:[]});
a.acknowledge(x);
assert.equal(a.read().changes.length,1,'Acknowledging later mutation must not discard earlier pending change');
assert.equal(a.read().changes[0].items[0].notes,'manual');
assert.throws(()=>createTripTimelineJournal(storage,{tripId:'../escape'}));
assert.throws(()=>createTripTimelineJournal(storage,{tripId:'vn-real',environment:'production-other'}));
console.log('PASS: trip/environment isolation, exact ack, legacy untouched, invalid IDs blocked');
