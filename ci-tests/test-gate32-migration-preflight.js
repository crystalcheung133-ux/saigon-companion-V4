'use strict';
const assert=require('node:assert/strict');
const {createTimelineJournal}=require('../timeline-sync-journal');
const {createTripTimelineJournal}=require('../timeline-trip-journal');
global.createTimelineJournal=createTimelineJournal;global.createTripTimelineJournal=createTripTimelineJournal;
const {inspectLegacyTimelineJournal}=require('../timeline-journal-migration');
const map=new Map();let writes=0;
const storage={getItem:k=>map.get(k)??null,setItem:(k,v)=>{writes++;map.set(k,v)}};
let p=inspectLegacyTimelineJournal(storage,{tripId:'test'});
assert.equal(p.status,'NO_PENDING_CHANGES');assert.equal(writes,0);
createTimelineJournal(storage).enqueue({day:'4',items:[{id:'manual',notes:'never overwrite'}]});
const before=map.get('vn_timeline_pending_v1'),n=writes;
p=inspectLegacyTimelineJournal(storage,{tripId:'test'});
assert.equal(p.status,'MANUAL_OWNERSHIP_REVIEW_REQUIRED');assert.equal(p.canAutoMigrate,false);assert.equal(writes,n);
assert.equal(map.get('vn_timeline_pending_v1'),before);
createTripTimelineJournal(storage,{tripId:'test'}).enqueue({day:'5',items:[]});
p=inspectLegacyTimelineJournal(storage,{tripId:'test'});
assert.equal(p.legacyCount,1);assert.equal(p.scopedCount,1);assert.equal(p.status,'MANUAL_OWNERSHIP_REVIEW_REQUIRED');
assert.throws(()=>inspectLegacyTimelineJournal(storage,{}));
map.set('vn_timeline_pending_v1','{broken');assert.throws(()=>inspectLegacyTimelineJournal(storage,{tripId:'test'}),/corrupt/);
console.log('PASS: legacy preflight is read-only, explicit trip, fail-closed, no silent migration');
