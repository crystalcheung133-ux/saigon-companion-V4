const assert=require('node:assert/strict');
const fs=require('node:fs');const path=require('node:path');
const root=path.resolve(__dirname,'..');
const {createTimelineJournal}=require('../timeline-sync-journal');
const makeStorage=()=>{const data=new Map();return {data,getItem:k=>data.has(k)?data.get(k):null,setItem:(k,v)=>data.set(k,v)};};
const storage=makeStorage();const j=createTimelineJournal(storage);
const batch=[{day:'3',items:[{id:'a',notes:'keep user notes'}]},{day:'4',items:[]}];
assert.deepEqual(j.enqueueBatch(batch),[1,2]);
assert.deepEqual(j.read().changes.map(x=>x.day),['3','4']);
batch[0].items[0].notes='changed later';assert.equal(j.read().changes[0].items[0].notes,'keep user notes');
const before=storage.getItem('vn_timeline_pending_v1');
assert.throws(()=>j.enqueueBatch([{day:'5',items:[]},{day:'6',items:null}]));
assert.equal(storage.getItem('vn_timeline_pending_v1'),before);
const bad=makeStorage();const jb=createTimelineJournal({...bad,setItem(){throw Error('quota');}});
assert.throws(()=>jb.enqueueBatch(batch));assert.equal(bad.getItem('vn_timeline_pending_v1'),null);
const html=fs.readFileSync(path.join(root,'day.html'),'utf8');
assert.match(html,/journal\.enqueueBatch\(timelineChanges\.map/);
assert.doesNotMatch(html,/timelineChanges\.forEach\(change=>journal\.enqueue/);
const fresh=createTimelineJournal(storage);assert.equal(fresh.read().changes.length,2);
fresh.acknowledge(1);assert.equal(fresh.read().changes.length,1);
console.log('Gate20 atomic multi-day journal: PASS');
